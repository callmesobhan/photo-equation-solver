// Usage: node build-node.mjs [output.cjs]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readSources } from './lib-body.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const out = process.argv[2] || path.join(here, '..', 'mcp-server', 'lib', 'solver.cjs');
const { body } = readSources();
const text = `// GENERATED by dev/build-node.mjs from dev/src: do not edit.
// Photo Equation Solver. Copyright (c) 2026 Sobhan Shahbazi. Proprietary: see LICENSE.
'use strict';
module.exports = function createSolver(document, console) {
  if (!console) console = { log() {}, error() {} };
  const window = { __noAnswerCard: true };
${body}
  return window;
};
`;
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, text);
console.log('wrote', out, (text.length / 1024).toFixed(1) + ' KB');
